#!/usr/bin/env python3
"""gen_font.py - builds font_dejavu.h, the viewer's built-in fonts.

The viewer draws its text with SDL2 and stb_truetype (third_party/stb): no
SDL_ttf, no font file to ship. This embeds DejaVu Sans and DejaVu Sans Bold,
cut down to printable ASCII (pyftsubset, fonttools); menu.h rasterizes each
glyph at the exact pixel size it is drawn at. DejaVu's licence (Bitstream
Vera, with the DejaVu changes public domain) allows this; its text ships in
the Windows zip's licenses folder.

    python3 tools/raw-recv/gen_font.py      # rewrites tools/raw-recv/font_dejavu.h
"""
import os
import subprocess
import tempfile

FONTS = [
    ("font_regular", ["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/TTF/DejaVuSans.ttf"]),
    ("font_bold", ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf"]),
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_dejavu.h")


def subset(path):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "f.ttf")
        subprocess.run(["pyftsubset", path, "--unicodes=U+0020-007E", "--no-hinting",
                        "--layout-features=kern", "--output-file=" + out], check=True)
        with open(out, "rb") as f:
            return f.read()


def main():
    with open(OUT, "w") as f:
        f.write("/* font_dejavu.h - generated by gen_font.py, do not edit.\n")
        f.write(" * DejaVu Sans / DejaVu Sans Bold (Bitstream Vera licence; DejaVu changes\n")
        f.write(" * public domain), printable ASCII only, as TrueType files. */\n")
        for name, paths in FONTS:
            data = subset(next(p for p in paths if os.path.exists(p)))
            f.write("static const unsigned char %s[%d] = {\n" % (name, len(data)))
            for i in range(0, len(data), 40):
                f.write("".join("%d," % b for b in data[i:i + 40]) + "\n")
            f.write("};\n")
            print("%s: %d bytes" % (name, len(data)))


if __name__ == "__main__":
    main()
