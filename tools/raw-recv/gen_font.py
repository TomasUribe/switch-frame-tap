#!/usr/bin/env python3
"""gen_font.py - builds font_dejavu.h, the viewer's built-in text (v0.5 menu).

The viewer draws its menu with SDL2 alone (no SDL_ttf, no font file to ship):
printable ASCII from DejaVu Sans and DejaVu Sans Bold, rendered here at the
sizes the interface uses (and at 2x for maximized/full-screen windows), stored
as 4-bit alpha, one tightly packed row per size. DejaVu's licence (Bitstream
Vera, with the DejaVu changes public domain) allows this; its text ships in the
Windows zip's licenses folder.

    python3 tools/raw-recv/gen_font.py      # rewrites tools/raw-recv/font_dejavu.h
"""
import os
from PIL import Image, ImageDraw, ImageFont

# The interface's text sizes. The same set at 2x covers a maximized or
# full-screen window on a 2560x1440 display without scaling the glyphs.
SIZES = (13, 15, 17, 20, 24, 30)
SCALES = (1, 2)
FONTS = [
    (0, "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    (1, "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
]
FIRST, LAST = 32, 126
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_dejavu.h")


def render_row(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    h = ascent + descent
    glyphs = []
    metrics = []
    x = 0
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch)
        w = max(r, adv, 1)
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
        metrics.append((x, im.width, adv))
        glyphs.append(im)
        x += im.width + 1
    row = Image.new("L", (x, h), 0)
    for im, (gx, _, _) in zip(glyphs, metrics):
        row.paste(im, (gx, 0))
    return row.tobytes(), metrics, h, x


def pack4(data):
    out = bytearray()
    for i in range(0, len(data) - 1, 2):
        out.append(((data[i] >> 4) << 4) | (data[i + 1] >> 4))
    if len(data) & 1:
        out.append((data[-1] >> 4) << 4)
    return bytes(out)


def main():
    row_sizes = sorted(set(s * scale for s in SIZES for scale in SCALES))
    rows = []
    atlas = bytearray()
    for bold, path in FONTS:
        for size in row_sizes:
            data, metrics, h, w = render_row(path, size)
            packed = pack4(data)
            rows.append((bold, size, w, h, len(atlas), len(packed), metrics))
            atlas += packed
    with open(OUT, "w") as f:
        f.write("/* font_dejavu.h - generated by gen_font.py, do not edit.\n")
        f.write(" * DejaVu Sans / DejaVu Sans Bold (Bitstream Vera licence; DejaVu changes\n")
        f.write(" * public domain), ASCII %d-%d: rows at %s px, 4-bit alpha. */\n"
                % (FIRST, LAST, ", ".join(str(s) for s in row_sizes)))
        f.write("#define FONT_FIRST %d\n#define FONT_LAST %d\n" % (FIRST, LAST))
        f.write("#define FONT_ROWS %d\n" % len(rows))
        f.write("static const int font_row_px[FONT_ROWS] = { %s };\n"
                % ", ".join(str(r[1]) for r in rows))
        f.write("static const int font_row_bold[FONT_ROWS] = { %s };\n"
                % ", ".join(str(r[0]) for r in rows))
        f.write("static const int font_row_w[FONT_ROWS] = { %s };\n"
                % ", ".join(str(r[2]) for r in rows))
        f.write("static const int font_row_h[FONT_ROWS] = { %s };\n"
                % ", ".join(str(r[3]) for r in rows))
        f.write("static const unsigned int font_row_off[FONT_ROWS] = { %s };\n"
                % ", ".join(str(r[4]) for r in rows))
        f.write("static const unsigned int font_row_len[FONT_ROWS] = { %s };\n"
                % ", ".join(str(r[5]) for r in rows))
        f.write("/* per row, per glyph: x in the row, width, advance */\n")
        f.write("static const unsigned short font_glyphs[FONT_ROWS][%d][3] = {\n" % (LAST - FIRST + 1))
        for r in rows:
            f.write("  {" + ",".join("{%d,%d,%d}" % g for g in r[6]) + "},\n")
        f.write("};\n")
        f.write("static const unsigned char font_atlas[%d] = {\n" % len(atlas))
        for i in range(0, len(atlas), 40):
            f.write("".join("%d," % b for b in atlas[i:i + 40]) + "\n")
        f.write("};\n")
    print("%s: %d rows, %s px, %d bytes" % (OUT, len(rows), row_sizes, len(atlas)))


if __name__ == "__main__":
    main()
